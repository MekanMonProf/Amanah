<h2>تسجيل عملية شراء</h2>

<p>
    من ملف المستثمر، <strong>+ شراء جديد</strong>. تختار الفئة — تجارية أو وقف —
    وعدد الأسهم والتاريخ وطريقة الدفع. ويُستنتج المبلغ من سعر السهم الساري.
</p>

<p>
    وإن لم يكن حساب الفئة المختارة موجوداً بعد، فُتح في أثناء ذلك. فقد يدخل
    المستثمر إذن عبر شراء وقفي ولا يكون له حساب تجاري قط.
</p>

<p class="note">
    <strong>التاريخ مهم.</strong> الشراء المسجَّل في الأيام الأخيرة من الشهر لا
    يعطي حقاً في الربح إلا ابتداءً من الشهر التالي. ويُضبط عدد الأيام في
    <strong>الأرباح ← قاعدة الاستحقاق في آخر الشهر</strong>. أدخل التاريخ الحقيقي
    للشراء، لا تاريخ الإدخال.
</p>

<h2>تعزيز رصيد</h2>

<p>
    <strong>التعزيز</strong>، في ترويسة الحساب، يُستعمل حين يدفع المستثمر مالاً دون
    أن يشتري في الحال: فيرتفع رصيده المالي، ويقع الشراء لاحقاً.
</p>

<p>
    و<strong>الشراء بالرصيد</strong> يفعل العكس: يحوّل رصيداً متكوّناً سلفاً إلى
    أسهم، دون انتظار التوزيع التالي. ولا يظهر الزرّ إلا في الحسابات التي أُطفئ فيها
    إعادة الاستثمار التلقائي — أما في غيرها فتتم العملية من نفسها كل شهر.
</p>

<h2>صرف مال لمستثمر</h2>

<p>
    <strong>الصرف</strong> يُخرج المال من الرصيد المالي إلى المستثمر. ويحمل القيد
    طريقة الدفع ويُنتج <strong>إيصالاً</strong> بصيغة PDF.
</p>

<p>
    ويختفي الزرّ في الفئات التي لا يُسمح فيها بصرف الأرباح. والأَولى ألا تُعرض
    العملية أصلاً من أن تُرفض بعد ذلك.
</p>

<h2>إهداء أسهم</h2>

<p>
    <strong>الهبة</strong> تنقل أسهماً أو رصيداً من حساب إلى آخر دون مقابل مالي
    للواهب. ولها صورتان:
</p>

<ul>
    <li><strong>هبة أسهم</strong>: تنتقل ملكية الأسهم.</li>
    <li><strong>هبة الرصيد</strong>: المال المتاح هو ما يُتنازَل عنه.</li>
</ul>

<p>
    وثمة حالة خاصة عند الشراء: <strong>الهدية الوقفية</strong>. يدفع الشراءَ شخصٌ
    ويُسنَد إلى الوقف الخيري باسم شخص آخر — ترحّماً على متوفَّى، أو تكريماً لحيّ.
    ولا تمنح هذه الأسهم المكرَّمَ أي حق في الملكية؛ وتظهر في ملفه في قسم مستقل.
</p>

<p class="note">
    <strong>الهبة نهائية.</strong> لا سبيل إلى إلغائها: وحده قيد تسوية، مقصور على
    الإدارة العليا، يمكنه تدارك الخطأ — وهو يترك أثراً، وذلك هو المقصود.
</p>

<h2>تصحيح خطأ</h2>

<p>
    <strong>التسوية</strong>، خلف قائمة <code>⋯</code> في ترويسة الحساب، مقصورة على
    الإدارة العليا والشؤون الإدارية. تكتب سطراً يصحّح الرصيد، مع سببه. لا شيء
    يُعاد كتابته ولا شيء يُمحى: يبقى الخطأ وتصحيحه كلاهما مقروءَين في السجل.
</p>
