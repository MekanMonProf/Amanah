<h2>تسجيل الدخول</h2>

<p>
    يفتح التطبيق على شاشة تسجيل الدخول. يعمل معرّفان اثنان:
    <strong>بريدك الإلكتروني</strong>، أو <strong>رقم الهاتف</strong> المسجَّل في
    ملفك. معظم المستثمرين ليس لديهم بريد إلكتروني، فيدخلون برقم هاتفهم.
</p>

<p>
    يمكن كتابة الرقم بأي صيغة: <code>77 123 45 67</code> و
    <code>00221771234567</code> و <code>+221771234567</code> كلها تدلّ على الرقم
    نفسه، والتطبيق يردّها إلى صيغة واحدة قبل البحث عنها.
</p>

<p class="note">
    <strong>الدخول لأول مرة.</strong> كلمة المرور التي ينشئها المدير مؤقتة: سيطلب
    منك التطبيق اختيار غيرها قبل أن يسمح لك بالدخول. هذا أمر طبيعي، وهو سبب كون
    كلمة المرور التي وصلتك بالرسالة لا تصلح إلا مرة واحدة.
</p>

<h2>التعرّف على الشاشة</h2>

<p>
    يجمع الشريط الجانبي كل ما لك حق الوصول إليه، مرتَّباً حسب المجال —
    <strong>الإدارة</strong> و<strong>المالية</strong> و<strong>الشؤون
    الإدارية</strong> و<strong>المساعدة</strong>. لا ترى إلا المداخل التي يسمح بها
    دورك: الشريط القصير ليس شريطاً ناقصاً.
</p>

<ul>
    <li>السهم أعلى الشريط يطويه إلى أيقونات، لكسب مساحة في العرض.</li>
    <li>على الهاتف يصبح الشريط درجاً، وتنتقل المداخل الأكثر استعمالاً إلى أسفل الشاشة.</li>
    <li>يذكّر أعلى كل صفحة، بحروف صغيرة، بالمجال الذي أنت فيه.</li>
</ul>

<h2>تغيير اللغة</h2>

<p>
    تُختار اللغات الثلاث — الفرنسية والإنجليزية والعربية — من أعلى اليسار. يُحفظ
    الاختيار على حسابك: تختاره مرة واحدة. بالعربية ينقلب التطبيق بكامله، فينتقل
    الشريط إلى اليمين وتُقرأ الجداول من اليمين إلى اليسار.
</p>

<p>
    قبل تسجيل الدخول، يوجد المحدِّد نفسه أسفل الاستمارة. ولا يدوم الاختيار حينها
    إلا مدة الزيارة، لعدم وجود حساب يُسجَّل فيه.
</p>

<h2>حسابك</h2>

<p>
    في أسفل الشريط، يفتح اسمك قائمة قصيرة: <strong>الملف الشخصي</strong> لتغيير
    كلمة المرور أو اللغة أو لتفعيل التحقق بخطوتين، و<strong>تسجيل الخروج</strong>.
</p>

<p class="note">
    <strong>إذا تعذّر عليك الدخول.</strong> لا تحاول أكثر من خمس مرات في شاشة
    الدخول: بعدها يُغلق الوصول بضع دقائق. مرّ بدل ذلك عبر <strong>الاتصال
    بالدعم</strong>، أو اطلب من مديرك إعادة تعيين كلمة مرورك.
</p>
