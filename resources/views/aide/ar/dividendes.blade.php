<h2>المبدأ</h2>

<p>
    تحدّد المؤسسة كل شهر <strong>ربحاً لكل سهم</strong> — واحداً للأسهم التجارية
    وآخر لأسهم الوقف. ويضرب التطبيق هذا المعدّل في عدد الأسهم التي كان يملكها كل
    حساب خلال الفترة، ثم يكتب الربح.
</p>

<p>
    ويُحدَّد المعدّل <strong>مرة واحدة</strong> لشهر بعينه. وهو نهائي: فالخطأ
    يُصلَح بتصحيح موثَّق، لا بإعادة كتابة صامتة.
</p>

<h2>التوزيع</h2>

<ol>
    <li>افتح <strong>الأرباح</strong>.</li>
    <li>اختر الشهر المعني.</li>
    <li>أدخل الربح لكل سهم، التجاري والوقفي.</li>
    <li>اضغط <strong>احسب ووزّع</strong>.</li>
</ol>

<p class="note">
    <strong>كل تشغيل يعيد تمثيل السجل كله</strong>، لا الشهر المختار وحده. فالحساب
    الذي فُتح لاحقاً يستدرك بذلك كل الأشهر التي فاتته، بالمعدّل الذي كان سارياً في
    كل فترة. والحساب الذي قبض ربحه عن شهر لا يقبضه مرتين.
</p>

<h2>قاعدتا الطرفين</h2>

<p>
    للشهر طرفان، ولكل طرف قاعدته، تُضبط في صفحة الأرباح.
</p>

<h3>عند الدخول — قاعدة الاستحقاق في آخر الشهر</h3>

<p>
    الشراء الذي يتم في الأيام الأخيرة من الشهر لا يُحتسب إلا ابتداءً من الشهر
    التالي. وعدد الأيام قابل للضبط؛ وعند الصفر يُحتسب كل شراء في الحال.
</p>

<h3>عند الخروج — قاعدة الخروج في أثناء الشهر</h3>

<p>
    الاسترداد الذي يتم في أثناء الشهر يدع الأسهم تنال ربح ذلك الشهر. وهذه هي ممارسة
    المؤسسة: من خرج في اليوم الخامس عشر يقبض الشهر كاملاً. والضبط الافتراضي 31
    يوماً، أي الشهر بتمامه؛ وعند الصفر تتوقف الأسهم عن الاحتساب فور الاسترداد.
</p>

<p>
    وتُقرأ هاتان القاعدتان على النحو نفسه في حساب الأرباح وفي أمر التحقق من
    الاتساق: فلا يمكن أن تتباعدا.
</p>

<h2>تصحيح معدّل</h2>

<p>
    في سجل المعدّلات، يفتح <strong>تصحيح التجاري</strong> و<strong>تصحيح
    الوقف</strong> تصحيح فترة سبق تحديدها. ويعيد التطبيق حساب الأرباح المعنية ويكتب
    الفارق — زيادة أو نقصاناً — في كل حساب متأثر.
</p>

<p class="note">
    <strong>تحقّق من عدد الحسابات المعنية</strong> قبل التأكيد. فالتصحيح على شهر
    قديم يمسّ كل من كان يملك أسهماً في ذلك التاريخ، بمن فيهم من خرجوا بعده.
</p>

<h2>ما يصير إليه الربح</h2>

<p>
    يقع في الرصيد المالي للحساب. وما يؤول إليه بعد ذلك يتوقف على إعادة الاستثمار
    التلقائي: إن كانت مفعّلة اشترى أسهماً كاملة بمجرد أن يسمح الرصيد، واحتفظ
    بالباقي للشهر التالي؛ وإن كانت مطفأة انتظر قراراً.
</p>
