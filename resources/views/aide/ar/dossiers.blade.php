<h2>فتح ملف</h2>

<p>
    من <strong>المستثمرون</strong>، لا يطلب زرّ <strong>ملف جديد</strong> إلا
    الضروري: اسم ورقم. وهذا مقصود — لا ينبغي للاكتتاب أن ينتظر اكتمال الأوراق.
    ويُدخَل الباقي لاحقاً.
</p>

<p>
    يمنح التطبيق معرّف الملف. ويمكن كتابة رقم الهاتف بأي صيغة: فهو يُردّ إلى الصيغة
    الدولية قبل حفظه.
</p>

<h2>استكمال الملف</h2>

<p>
    يُنبَّه على الملف الذي تنقصه وثيقة مطلوبة: ففي أعلى صفحته سطر يذكر ما ينقص
    ويقود مباشرة إلى الاستمارة. وفي قائمة <strong>المستثمرون</strong> مرشِّح يجمعها
    كلها.
</p>

<p>
    وما يُطلب ليس ثابتاً: فتبويب <strong>حقول الملف</strong> في الإعدادات هو ما
    يقرّر، من فهرس أوسع، أي السطور تُحتسب. والوثيقة التي يُزال تحديدها تختفي من
    التنبيه دون أن تختفي من الاستمارة.
</p>

<p class="note">
    <strong>لا شيء يُمنَع.</strong> يبقى الملف غير المكتمل صالحاً للاستعمال تماماً:
    يمكن تسجيل مشتريات فيه، وصرف أرباح له، واسترداد أسهمه. التنبيه تذكير لا قفل —
    فإيقاف التحصيل من أجل وثيقة ناقصة يكلّف أكثر من المخاطرة التي نريد تقليلها.
</p>

<h2>منح الدخول إلى البوابة</h2>

<p>
    في الملف، يفتح <strong>إنشاء دخول إلى بوابة المستثمر</strong> حساباً للمستثمر.
    ويولّد التطبيق كلمة مرور مؤقتة ويعرضها على الشاشة، مع زرّ يجهّز رسالة واتساب.
</p>

<ol>
    <li>اضغط زرّ واتساب: يفتح تطبيقك والرسالة مكتوبة سلفاً.</li>
    <li>أنت من يرسلها، من حسابك الخاص.</li>
    <li>سيضطر المستثمر إلى تغيير كلمة المرور هذه عند أول دخول.</li>
</ol>

<p>
    ثلاث حالات لا اثنتان: يمكن <strong>سحب</strong> الدخول دون محوه، ثم إعادته.
    والسحب يقطع الجلسة الجارية؛ أما الملف والأسهم والسجل فلا تُمسّ.
</p>

<p class="note">
    <strong>المنصة لا ترسل شيئاً من تلقاء نفسها.</strong> هي تجهّز الرسالة وأنت
    ترسلها. لا إرسال تلقائي، ومن ثَمّ لا إثبات للإرسال: فإن قال المستثمر إنه لم
    يتلقَّ شيئاً، فراجع محادثتك أنت على واتساب.
</p>

<h2>تغيير المدير</h2>

<p>
    يحمل قسم <strong>المدير</strong> في الملف رابط <strong>تغيير</strong>، وهو
    مقصور على الإدارة العليا والشؤون الإدارية. ويُسجَّل النقل في سجل التدقيق، مع
    اسم السابق واللاحق.
</p>

<h2>تعطيل ملف</h2>

<p>
    في أسفل الصفحة، تحت <strong>إجراءات نادرة</strong>. التعطيل يقطع الدخول إلى
    البوابة ويخرج الملف من القوائم الجارية، دون محو أي شيء. والعملية قابلة
    للتراجع: إذ يعرض الزرّ نفسه عندئذ <strong>إعادة التفعيل</strong>.
</p>

<p>
    أما الوفاة فلا تُعالَج هنا بل عبر <strong>الإبلاغ عن وفاة</strong>، الذي يفتح
    ملف ميراث. انظر الصفحة المخصصة لذلك.
</p>
