<h2>التصدير الشامل</h2>

<p>
    تجمع شاشة <strong>التصدير</strong> المخرجات التي تشمل القاعدة كلها: المشتريات
    والقيود المالية والاستردادات وسجل التدقيق. ولكل منها صيغتان:
    <strong>CSV</strong> — لمواصلة العمل في جدول حسابات — و<strong>PDF</strong> —
    للإرسال أو الحفظ.
</p>

<p>
    ويحدّد حقلا التاريخ الفترة. وإن تُركا فارغين أعطيا السجل كله.
</p>

<h2>تصدير حساب بعينه</h2>

<p>
    توجد المخرجات نفسها حساباً حساباً، من ملف المستثمر: زرّا <strong>CSV</strong>
    و<strong>PDF</strong> فوق كل جدول — سجل المشتريات، قيود الحساب المالي — لا
    يصدّران إلا ما يعلوانه، بما في ذلك المرشِّحات.
</p>

<h2>كشف الحساب</h2>

<p>
    في أسفل ملف المستثمر، يُنتج <strong>كشف الحساب</strong> وثيقة تحمل ترويسة
    المؤسسة، تجمع وضعيته ومشترياته وحركاته خلال الفترة المطلوبة. وهي الوثيقة التي
    تُرسَل إلى مستثمر يسأل «أين أقف».
</p>

<p>
    وللمستثمر الذي له دخول إلى البوابة أن يستخرجها بنفسه من
    <strong>مساحتي</strong>.
</p>

<h2>الشهادات والإيصالات</h2>

<ul>
    <li>تتوفّر <strong>شهادة شراء</strong> على كل سطر شراء.</li>
    <li>يتوفّر <strong>إيصال</strong> على كل صرف.</li>
    <li>تصحب <strong>شهادة ميراث</strong> كل صرف لوارث.</li>
</ul>

<p>
    وتُفتح هذه الوثائق كذلك عبر <strong>رابط موقَّع</strong> صالح مدةً محدودة، لا
    يُلزم المتلقّي بامتلاك حساب في المنصة.
</p>

<h3>ماذا تحمل شهادة الشراء</h3>

<p>
    إلى جانب الشراء الذي تُثبته، تُذكّر الشهادة بـ<strong>عمليات التملّك السابقة على
    الحساب</strong>: التاريخ والرقم والطبيعة وعدد الأسهم والمبلغ، مع المجموع في ذلك
    التاريخ. فالاكتتاب يتمّ غالبًا على دفعات، وبذلك يجد المساهم مجموعها في وثيقة
    واحدة. ولا يظهر هذا الملخّص في أول شراء، إذ لا سابق له يُذكَر.
</p>

<p>
    ويقف عند تاريخ الشراء المُثبَت لا عند اليوم: فالشهادة تقول ما كان صحيحًا يوم
    استُحقّت، وطبعتان من الوثيقة نفسها تتشابهان ولو فصلت بينهما شهور.
</p>

<p class="note">
    <strong>المُتملَّك غير المملوك.</strong> فإذا عرف الحساب شطبًا أو هبة، أضافت
    الشهادة عدد الأسهم المملوكة فعلاً في ذلك التاريخ، وبيّنت مصدر الفارق. وكذلك
    يُذكر على حدة ما جاء من إعادة استثمار الأرباح: فهو لا يقابل أي دفع من المساهم.
</p>

<p class="note">
    <strong>في هدية الوقف، لا يرى كل واهب إلا هداياه.</strong> فالأسهم الموهوبة
    تُقيَّد في حساب الوقف المؤسسي الذي يتلقّى هدايا الواهبين جميعًا. ولذلك لا تلخّص
    الشهادة إلا هدايا صاحبها، ولا تقول شيئًا عن حجم ذلك الحساب.
</p>

<p class="note">
    <strong>التصدير صورة لا رابط حيّ.</strong> فملف CSV صادر اليوم لا يحدّث نفسه.
    أرّخ ملفاتك، أو أعد استخراجها لحظة استعمالها: فكشف عمره ثلاثة أشهر لم يعد يقول
    وضعية اليوم.
</p>
