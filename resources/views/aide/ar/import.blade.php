<h2>ما يقدر عليه الاستيراد</h2>

<p>
    يستعيد <strong>الاستيراد</strong> ملف إكسل (<code>.xlsx</code>) أو CSV لإنشاء
    مديرين أو مستثمرين أو مشتريات أو قيود مالية دفعة واحدة. وهو لاستعادة السجلات
    القائمة، لا للإدخال اليومي.
</p>

<h2>الترتيب مهم</h2>

<p>
    تُستورَد العائلات الأربع بهذا الترتيب، لا بغيره:
</p>

<ol>
    <li><strong>المديرون</strong></li>
    <li><strong>المستثمرون</strong></li>
    <li><strong>مشتريات الأسهم</strong></li>
    <li><strong>القيود المالية</strong></li>
</ol>

<p>
    تستند كل خطوة إلى سابقتها: فالشراء يحتاج إلى مستثمره، والمستثمر قد يُربط
    بمديره. وعكس الترتيب يُفشل السطور التي تحيل على ما لم يوجد بعد.
</p>

<h2>مجرى العمل</h2>

<ol>
    <li><strong>نزِّل قالب CSV</strong> الخاص بالعائلة المعنية. يحمل العناوين المنتظَرة وسطر مثال يُستبدَل.</li>
    <li>املأه ببياناتك، مع إبقاء السطر الأول كما هو.</li>
    <li><strong>أودِع الملف.</strong> يقرؤه التطبيق ويعرض جدول مراجعة.</li>
    <li>اقرأ هذا الجدول: يذكر، سطراً سطراً، ما سيُنشأ وما سيُتجاوَز ولماذا.</li>
    <li>صادِق.</li>
</ol>

<p class="note">
    <strong>لا يُحفظ شيء قبل مصادقتك.</strong> إيداع الملف ليس إلا قراءة له. وما
    دمت لم تصادق على جدول المراجعة، فقاعدة البيانات لم تتغير — يمكنك تصحيح الملف
    وإعادة الكرّة بقدر ما تحتاج.
</p>

<h2>قراءة جدول المراجعة</h2>

<p>
    يظهر فيه كل سطر من الملف بمآله. والرفض مشروح: مستثمر غير موجود، أو تاريخ غير
    مقروء، أو تكرار. صحِّح الملف المصدر لا قاعدة البيانات: فتحتفظ بأثر لما
    استوردته.
</p>

<h2>ما لا يفعله الاستيراد</h2>

<ul>
    <li><strong>لا يسجّل الأرباح</strong>. فهي تُحسب من شاشة الأرباح، التي تعيد تمثيل السجل كله وتطبّق قاعدتَي الطرفين.</li>
    <li>لا يطمس ملفاً قائماً: فالتكرار يُنبَّه عليه ولا يُدمَج.</li>
    <li>لا يخمّن صيغة تاريخ ملتبسة. اكتب التواريخ هكذا: <code>يوم/شهر/سنة</code>.</li>
</ul>

<p class="note">
    <strong>تُسجَّل القيود بترتيب سطور الملف.</strong> والرصيد بعد كل قيد يُثبَّت
    لحظة كتابته: فالملف الذي لا تتبع سطوره الترتيب الزمني سينتج أرصدة وسيطة محيّرة،
    وإن كان الرصيد النهائي صحيحاً. رتِّب حسب التاريخ قبل الاستيراد.
</p>
