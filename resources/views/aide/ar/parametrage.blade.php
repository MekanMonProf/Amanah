<h2>الوصول إلى الوحدات</h2>

<p>
    تقاطع الشبكة بين <strong>الأدوار</strong> — الإدارة العليا، الشؤون الإدارية،
    إدارة الحسابات، الاطّلاع — و<strong>وحدات</strong> التطبيق. وفيها ثلاثة
    مستويات: لا شيء، واطّلاع، وكتابة.
</p>

<p>
    والدور الذي لا وصول له لا يرى المدخل في الشريط الجانبي ولا يستطيع بلوغ الصفحة،
    ولو كتب عنوانها. فالجدول نفسه هو ما يأمر القائمة والمسارات: فلا يمكن أن
    يتناقضا.
</p>

<p class="note">
    <strong>يحتفظ المدير العام دائماً بالوصول إلى الإعدادات.</strong> فلولا هذا
    القفل لانغلقت شبكة سيّئة الضبط على نفسها، ولاحتاج الخروج منها إلى المرور بقاعدة
    البيانات.
</p>

<h2>حسابات المستخدمين</h2>

<p>
    إنشاء حساب، وتغيير دوره، وتعطيله، وإعادة تعيين كلمة مروره. وكلمة المرور
    المنشأة هنا مؤقتة: سيضطر صاحبها إلى اختيار غيرها عند أول دخول.
</p>

<p>
    والتعطيل أفضل من الحذف: فالحساب يكفّ عن فتح الباب، لكن كل ما فعله يبقى منسوباً
    إلى أحد في سجل التدقيق.
</p>

<h2>الإعدادات المالية</h2>

<p>
    سعر السهم، وقاعدتا طرفَي الربح:
</p>

<ul>
    <li><strong>قاعدة الاستحقاق في آخر الشهر</strong> — الشراء في الأيام الأخيرة من الشهر لا يُحتسب إلا من الشهر التالي.</li>
    <li><strong>قاعدة الخروج في أثناء الشهر</strong> — الاسترداد في أثناء الشهر يدع الأسهم تنال ربح ذلك الشهر.</li>
</ul>

<p>
    وتُضبط كلتاهما كذلك من صفحة الأرباح، حيث تُستعملان.
</p>

<h2>حقول الملف</h2>

<p>
    هنا يُقرَّر، من فهرس أوسع، أي الوثائق يجب أن يتضمنها الملف ليُعَدّ مكتملاً.
    تحديد سطر يُدخله في التنبيه؛ وإزالة التحديد تُخرجه منه، دون حذفه من
    الاستمارة.
</p>

<p>
    وتذكر الشاشة، قبل الحفظ، كم ملفاً سيُنبَّه عليه بالضبط الحالي. فاستعن بذلك.
</p>

<p class="note">
    <strong>الإشارة التي تنطلق في كل مكان لا تشير إلى شيء.</strong> فإن كانت
    الملفات كلها تقريباً مُنبَّهاً على نقصها، فليست القاعدة هي ما يحتاج إلى تصحيح
    بل هذا الضبط: لا تطلب إلا الوثائق التي بدأ تحصيلها فعلاً، وحدِّد غيرها تباعاً.
</p>

<h2>المساعدة والدعم</h2>

<p>
    بيانات الاتصال التي يراها أحد أفراد الفريق عند طلب المساعدة، وعناوين مقاطع
    الفيديو المرافقة لدليل الاستخدام، وقائمة الطلبات الواردة.
</p>

<p>
    أما المستثمر فلا يصل إلى هنا: إذ يذهب طلبه إلى مديره الخاص. ولا يرجع إلى دعم
    المنصة إلا إذا لم يكن لملفه مدير مُسنَد.
</p>

<h2>سجل التدقيق</h2>

<p>
    ليس ضمن الإعدادات لكنه مكمّلها: فكل ضبط يتغيّر هنا يترك فيه سطراً، بمن غيّره
    ومتى وبالقيمة السابقة. والسجل لا يُكتب باليد ولا يُمحى.
</p>
