<h2>ما تراه عند الدخول</h2>

<p>
    تفتح <strong>مساحتي</strong> على وضعيتك: عدد الأسهم التجارية التي تملكها، وعدد
    أسهم الوقف، ومجموع أرصدتك. هذا هو الملخّص؛ أما التفصيل فيأتي أسفله، حساباً
    حساباً.
</p>

<h2>حساباتك</h2>

<p>
    قد يحمل الملف الواحد عدة حسابات. يعرض كل حساب فئته ورقمه، وما إذا كان إعادة
    الاستثمار التلقائي مفعّلاً فيه.
</p>

<ul>
    <li><strong>تجاري</strong>: الأسهم التي تملكها وتدرّ عليك ربحاً.</li>
    <li><strong>وقف</strong>: أسهم مُسنَدة إلى الوقف. لا تمنحك أي حق في الملكية.</li>
</ul>

<p>
    <strong>الأسهم المملوكة</strong> هو عدد الأسهم إلى اليوم. و<strong>رصيد
    الحساب</strong> هو المال المتاح: الأرباح التي لم يُعَد استثمارها ولم تُصرف بعد.
</p>

<h2>إعادة الاستثمار التلقائي</h2>

<p>
    حين يكون على <strong>نعم</strong>، يشتري ربحك أسهماً بمجرد أن يبلغ ثمن سهم
    كامل، وينتظر الباقي الشهر التالي. وهذا ما يفسّر ارتفاع عدد أسهمك من تلقاء نفسه
    من شهر إلى آخر.
</p>

<p>
    وحين يكون على <strong>لا</strong>، يتراكم الربح في الرصيد وأنت من يقرّر: تركه،
    أو الشراء، أو طلب الصرف.
</p>

<h2>مشترياتك وحركاتك</h2>

<p>
    يسرد جدول <strong>مشترياتي</strong> كل دخول للأسهم، بتاريخه وعدده ومبلغه. وتحمل
    كل سطر <strong>شهادة</strong> بصيغة PDF يمكنك فتحها والاحتفاظ بها.
</p>

<p>
    يعرض <strong>آخر الحركات</strong> آخر عشر قيود في حسابك: الأرباح بالأخضر، وما
    يخرج بالأحمر. ويظهر شراء الأسهم بالسالب — إذ يغادر المال الرصيد ليصير أسهماً.
</p>

<h2>كشف حسابك</h2>

<p>
    في أسفل الصفحة، يُنتج <strong>كشف الحساب</strong> ملف PDF كاملاً. اترك التاريخين
    فارغين للحصول على كامل السجل، أو حدِّد فترة — لإقرار، أو لسنة ميلادية.
</p>

<p class="note">
    <strong>هل فاجأك سطر؟</strong> لا تستنتج شيئاً قبل أن تسأل. زرّ <strong>الاتصال
    بالدعم</strong> يرسل سؤالك إلى مديرك، وأمامه التفاصيل. اذكر تاريخ السطر المعني
    ومبلغه.
</p>
