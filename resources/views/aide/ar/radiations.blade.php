<h2>استرداد أسهم</h2>

<p>
    يُخرج الاسترداد أسهماً من الحساب ويقيّد رأس المال المقابل في الرصيد المالي.
    ويبدأ من ملف المستثمر، عبر قائمة <code>⋯</code> في ترويسة الحساب، مدخل
    <strong>الاسترداد</strong>.
</p>

<p>
    ولا يظهر الزرّ في الفئات التي لا يُسمح فيها بالاسترداد — وأسهم الوقف، على وجه
    الخصوص، لا تُسترجَع.
</p>

<ol>
    <li>اذكر عدد الأسهم المستردّة والتاريخ الحقيقي للخروج.</li>
    <li>يُحسب رأس المال ويُقيَّد في الرصيد المالي للحساب.</li>
    <li>أما الصرف للمستثمر فعملية ثانية مستقلة.</li>
</ol>

<p class="note">
    <strong>الاسترداد ليس صرفاً.</strong> الاسترداد يضع المال في الرصيد؛ ويبقى هناك
    حتى يُخرجه <strong>صرف</strong>. والحساب المستردّ الذي لم يُصرف رصيده يظل
    ظاهراً في «الاستردادات المعلّقة» على لوحة القيادة.
</p>

<h2>صرف رأس المال</h2>

<p>
    في ترويسة الحساب، <strong>الصرف</strong>. تتعرّف الشاشة على أن الأمر يتعلق برأس
    مال استرداد وتُعلن ذلك. أدخل طريقة الدفع الحقيقية — نقداً أو تحويلاً أو Wave
    أو Orange Money — فستظهر في الإيصال.
</p>

<p>
    ويُنتج كل صرف <strong>إيصالاً</strong> بصيغة PDF يمكن تنزيله من سطر القيد،
    و<strong>شهادة</strong> يُطَّلع عليها برابط موقَّع لا يُلزم المتلقّي بامتلاك
    حساب.
</p>

<h2>تاريخ الاسترداد والربح</h2>

<p>
    الأسهم المستردّة في أثناء الشهر تنال ربح ذلك الشهر، وفق قاعدة الخروج المضبوطة
    في صفحة الأرباح. ولهذا يهمّ <strong>التاريخ الحقيقي</strong> للاسترداد: فإدخاله
    في أول الشهر التالي يحرم المستثمر شهراً هو من حقه.
</p>

<h2>العودة إلى السجل</h2>

<p>
    يحمل كل حساب قائمة استرداداته، بالرقم والتاريخ والكمية وطريقة التسوية. ويُصدَّر
    المجموع من <strong>التصدير</strong>، بصيغة CSV أو PDF، على فترة مختارة.
</p>

<p class="note">
    <strong>لا يُلغى الاسترداد</strong> من الشاشة. فإن كان خاطئاً، فقيد تسوية —
    مقصور على الإدارة العليا — هو ما يصحّح الرصيد، ويبقى التصحيح مقروءاً إلى جانب
    الخطأ.
</p>
