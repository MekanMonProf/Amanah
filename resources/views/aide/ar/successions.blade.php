<h2>الإبلاغ عن وفاة</h2>

<p>
    من ملف المستثمر، في الأسفل، تحت <strong>إجراءات نادرة</strong>:
    <strong>الإبلاغ عن وفاة</strong>. ينتقل الملف إلى حالة <em>متوفَّى</em>
    و<strong>تُجمَّد</strong> حساباته.
</p>

<p>
    والحساب المجمَّد لا يقبل أي عملية جارية: لا شراء ولا تعزيز ولا صرف ولا هبة ولا
    استرداد. ولا يمسّه إلا توزيع الميراث، عبر شاشته المخصصة.
</p>

<p class="note">
    <strong>يُقطع الدخول إلى البوابة.</strong> إن كان للمتوفَّى حساب دخول فاسحبه:
    يحتفظ الملف بزرّ <strong>سحب الدخول</strong> في حالة الوفاة، لأن هذا هو موضع
    نفعه الأكبر.
</p>

<h2>وثائق الميراث</h2>

<p>
    يتطلب ملف المتوفَّى وثائق أكثر من غيره: شهادة الوفاة، وللوكيل — أي أول وارث
    يُعيَّن — بطاقة هويته، وشهادة الإراثة أو إشهاد الشهرة، والوكالة الموقَّعة من
    الأسرة.
</p>

<p>
    وهذه الوثائق <strong>يُنبَّه عليها ولا تُشترط</strong>: فكثيراً ما يُفتح
    الميراث قبل أن تجمع الأسرة أوراقها، ومنعُ التعيين سيؤخّر كل ما سواه. وتُعدّ
    وثيقة الوكيل مقدَّمة بمجرد أن يحملها أحد الورثة — فملف الميراث هو ما يُحكم
    باكتماله، لا شخص بعينه.
</p>

<h2>تعيين الورثة</h2>

<p>
    <strong>المواريث</strong> في الشريط، ثم الملف المعني. ويتيح <strong>إدارة
    الميراث</strong> إضافة الورثة وتحديد نصيب كل واحد. ويقوم أول المعيَّنين بدور
    الوكيل.
</p>

<h2>التوزيع والصرف</h2>

<p>
    في الحسابات <strong>التجارية</strong>، تختار الأسرة، نصيباً نصيباً:
</p>

<ul>
    <li><strong>النقل</strong>: تنتقل الأسهم إلى ملف الوارث، فيصير مستثمراً بدوره. وإن لم يكن له ملف، فُتح له ملف.</li>
    <li><strong>الصرف</strong>: يُصفّى النصيب ويُدفع مالاً.</li>
</ul>

<p>
    أما الحسابات <strong>الوقفية</strong> فلا خيار فيها: يعود رأس المال إلى الوقف
    الخيري. فتلك الأسهم لم تكن قط مالاً موروثاً.
</p>

<p>
    ويُنتج كل صرف <strong>شهادة ميراث</strong> بصيغة PDF، باسم الوارث.
</p>

<p class="note">
    <strong>تحقّق من الأنصبة قبل إطلاق التوزيع.</strong> فما إن تُنقل الأسهم
    وتُكتب المصروفات حتى يصير الرجوع محتاجاً إلى قيود تسوية في عدة ملفات دفعة
    واحدة.
</p>
