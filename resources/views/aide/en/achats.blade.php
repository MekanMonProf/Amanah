<h2>Recording a purchase</h2>

<p>
    From an investor's file, <strong>+ New purchase</strong>. You choose the category
    — commercial or waqf — the number of shares, the date and the means of payment.
    The amount follows from the share price in force.
</p>

<p>
    If the account for the chosen category does not exist yet, it is opened along the
    way. An investor may therefore enter through a waqf purchase and never have a
    commercial account.
</p>

<p class="note">
    <strong>The date matters.</strong> A purchase recorded in the very last days of
    the month only earns a dividend from the following month. The number of days is
    set in <strong>Dividends → End-of-month eligibility rule</strong>. Enter the real
    date of the purchase, not the date of data entry.
</p>

<h2>Topping up a balance</h2>

<p>
    <strong>Top-up</strong>, on the account header, is for when the investor pays
    money in without buying straight away: their account balance rises, and the
    purchase will happen later.
</p>

<p>
    <strong>Buy with the balance</strong> does the opposite: it turns an existing
    balance into shares, without waiting for the next distribution. The button only
    appears on accounts where automatic reinvestment is off — on the others, the
    operation happens by itself each month.
</p>

<h2>Paying money to an investor</h2>

<p>
    <strong>Payout</strong> takes money out of the account balance and to the
    investor. The entry carries the means of payment and produces a
    <strong>receipt</strong> in PDF.
</p>

<p>
    The button disappears on categories where paying dividends out is not allowed.
    Better not to offer the operation than to refuse it afterwards.
</p>

<h2>Gifting shares</h2>

<p>
    <strong>Gift</strong> transfers shares or a balance from one account to another
    with no financial consideration for the giver. Two forms:
</p>

<ul>
    <li><strong>Gift of shares</strong>: the shares change owner.</li>
    <li><strong>Gift of the balance</strong>: it is the available money that is given.</li>
</ul>

<p>
    A special case exists at purchase: the <strong>waqf offering</strong>. The purchase
    is paid by one person and given to the charitable waqf in another's name — in
    memory of someone who has died, or in someone's honour. These shares confer no
    property right on the person honoured; they appear on their file in a separate
    block.
</p>

<p class="note">
    <strong>A gift is final.</strong> There is no cancelling it: only an adjustment
    entry, reserved for management, can make up for a mistake — and it leaves a trace,
    which is the point.
</p>

<h2>Correcting a mistake</h2>

<p>
    <strong>Adjustment</strong>, behind the <code>⋯</code> menu on the account header,
    is reserved for management and administration. It writes a line correcting the
    balance, with its reason. Nothing is rewritten, nothing is erased: the mistake and
    its correction both remain readable in the history.
</p>
