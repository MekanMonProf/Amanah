<h2>Signing in</h2>

<p>
    The application opens on the sign-in screen. Two identifiers work: your
    <strong>email address</strong>, or the <strong>phone number</strong> recorded on
    your file. Most investors have no email and sign in with their number.
</p>

<p>
    The number can be written however you like: <code>77 123 45 67</code>,
    <code>00221771234567</code> and <code>+221771234567</code> all mean the same
    number — the application reduces them to a single form before looking it up.
</p>

<p class="note">
    <strong>First sign-in.</strong> A password created by a manager is temporary: the
    application will ask you to choose another one before letting you in. That is
    normal, and it is why the password you received by message only works once.
</p>

<h2>Finding your way</h2>

<p>
    The left bar holds everything you have access to, grouped by area —
    <strong>Management</strong>, <strong>Finance</strong>,
    <strong>Administration</strong>, <strong>Help</strong>. You only see the entries
    your role allows: a short bar is not an incomplete one.
</p>

<ul>
    <li>The chevron at the top of the bar collapses it to icons, to gain width.</li>
    <li>On a phone, the bar becomes a drawer and the most frequent entries move to the bottom of the screen.</li>
    <li>The top of every page recalls, in small capitals, which area you are in.</li>
</ul>

<h2>Changing language</h2>

<p>
    The three languages — French, English, Arabic — are chosen at the top right. The
    choice is kept on your account: you make it once. In Arabic the application turns
    around entirely, the bar moves to the right and tables read right to left.
</p>

<p>
    Before you sign in, the same selector sits under the form. The choice then only
    lasts for the visit, for want of an account to record it on.
</p>

<h2>Your account</h2>

<p>
    At the bottom of the bar, your name opens a short menu:
    <strong>Profile</strong> to change your password, your language or to turn on
    two-factor authentication, and <strong>Sign out</strong>.
</p>

<p class="note">
    <strong>If you are locked out.</strong> Do not try more than five times on the
    sign-in screen: beyond that, access closes for a few minutes. Go through
    <strong>Contact support</strong> instead, or ask your manager to reset your
    password.
</p>
