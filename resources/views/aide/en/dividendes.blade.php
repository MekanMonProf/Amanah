<h2>The principle</h2>

<p>
    Each month, the house sets a <strong>profit per share</strong> — one for
    commercial shares, one for waqf shares. The application multiplies that rate by
    the number of shares each account held over the period, and writes the dividend.
</p>

<p>
    A rate is set <strong>once only</strong> for a given month. It is final: a mistake
    is repaired by a traced correction, not by a silent rewrite.
</p>

<h2>Distributing</h2>

<ol>
    <li>Open <strong>Dividends</strong>.</li>
    <li>Choose the month concerned.</li>
    <li>Enter the profit per share, commercial and waqf.</li>
    <li>Click <strong>Calculate and distribute</strong>.</li>
</ol>

<p class="note">
    <strong>Every run replays the whole history</strong>, not only the chosen month.
    An account opened after the fact thus catches up on every month it missed, at the
    rate in force for each period. An account that has already received its dividend
    for a month does not receive it twice.
</p>

<h2>The two edge rules</h2>

<p>
    A month has two ends, and each has its rule, adjustable on the dividends page.
</p>

<h3>On the way in — end-of-month eligibility rule</h3>

<p>
    A purchase made in the last days of the month only counts from the following
    month. The number of days is adjustable; at zero, every purchase counts
    immediately.
</p>

<h3>On the way out — mid-month exit rule</h3>

<p>
    A redemption made mid-month lets the shares earn that month's dividend. That is
    the practice of the house: whoever leaves on the 15th receives the whole month.
    The default setting is 31 days, that is, the full month; at zero, the shares stop
    counting as soon as they are redeemed.
</p>

<p>
    These two rules are read identically by the dividend calculation and by the
    consistency-check command: they cannot drift apart.
</p>

<h2>Correcting a rate</h2>

<p>
    In the history of rates, <strong>Correct com.</strong> and
    <strong>Correct waqf</strong> open the correction of a period already set. The
    application recalculates the dividends concerned and writes the difference — up or
    down — on every account affected.
</p>

<p class="note">
    <strong>Check the number of accounts concerned</strong> before confirming. A
    correction on an old month touches everyone who held shares on that date,
    including those who have left since.
</p>

<h2>What the dividend becomes</h2>

<p>
    It lands on the account balance. What happens to it next depends on automatic
    reinvestment: on, it buys back whole shares as soon as the balance allows, and
    keeps the remainder for the following month; off, it waits for a decision.
</p>
