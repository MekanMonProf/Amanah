<h2>Opening a file</h2>

<p>
    From <strong>Investors</strong>, the <strong>New file</strong> button asks only
    for the essentials: a name, a number. That is deliberate — a subscription must not
    wait for the papers to be gathered. The rest is entered later.
</p>

<p>
    The file identifier is assigned by the application. The phone number may be
    written in any form: it is reduced to the international format before being
    recorded.
</p>

<h2>Completing the file</h2>

<p>
    A file missing a required document is flagged: at the top of its page, a line
    states what is missing and leads straight to the form. The
    <strong>Investors</strong> list has a filter to find them all.
</p>

<p>
    What is required is not fixed: the <strong>File fields</strong> tab of the
    settings screen decides, from a wider catalogue, which lines count. A document
    unticked disappears from the flag without disappearing from the form.
</p>

<p class="note">
    <strong>Nothing is blocked.</strong> An incomplete file stays fully usable:
    purchases can be recorded on it, dividends paid to it, shares redeemed from it.
    The flag is a reminder, not a lock — stopping collection over a missing document
    would cost more than the risk it seeks to reduce.
</p>

<h2>Granting portal access</h2>

<p>
    On the file, <strong>Create investor portal access</strong> opens a sign-in
    account for the investor. The application generates a temporary password, shows it
    on screen, and offers a button that prepares the WhatsApp message.
</p>

<ol>
    <li>Click the WhatsApp button: your application opens, the message is already written.</li>
    <li>You send it yourself, from your own account.</li>
    <li>The investor will have to change that password on first sign-in.</li>
</ol>

<p>
    Three states, not two: access can be <strong>revoked</strong> without being
    erased, then restored. Revoking cuts the current session; the file, the shares and
    the history are untouched.
</p>

<p class="note">
    <strong>The platform sends nothing by itself.</strong> It prepares the message,
    you send it. No automatic sending, therefore no proof of sending: if the investor
    says they received nothing, check your own WhatsApp conversation.
</p>

<h2>Changing manager</h2>

<p>
    The <strong>Manager</strong> block of the file carries a <strong>Change</strong>
    link, reserved for management and administration. The transfer is written to the
    audit log, with the outgoing and incoming holder.
</p>

<h2>Deactivating a file</h2>

<p>
    At the bottom of the page, under <strong>Rare actions</strong>. Deactivating cuts
    portal access and takes the file out of the current lists, without erasing
    anything. The operation undoes itself: the same button then offers
    <strong>Reactivate</strong>.
</p>

<p>
    A death is not handled here but through <strong>Report a death</strong>, which
    opens an estate. See the corresponding page.
</p>
