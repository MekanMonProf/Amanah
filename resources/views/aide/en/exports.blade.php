<h2>Global exports</h2>

<p>
    The <strong>Exports</strong> screen gathers the outputs covering the whole
    database: purchases, account entries, redemptions, audit log. Each exists as
    <strong>CSV</strong> — to work on further in a spreadsheet — and as
    <strong>PDF</strong> — to pass on or to file.
</p>

<p>
    The two date fields bound the period. Left empty, they give the whole history.
</p>

<h2>One account's exports</h2>

<p>
    The same outputs exist account by account, from the investor's file: the
    <strong>CSV</strong> and <strong>PDF</strong> buttons above each table — purchase
    history, account entries — export only what they sit above, filters included.
</p>

<h2>The account statement</h2>

<p>
    At the bottom of an investor's file, <strong>Account statement</strong> produces a
    document on the letterhead of the house, gathering their holding, their purchases
    and their movements over the period requested. It is the document to send to an
    investor who asks "where do I stand".
</p>

<p>
    An investor with portal access can produce it themselves from
    <strong>My space</strong>.
</p>

<h2>Certificates and receipts</h2>

<ul>
    <li>A <strong>purchase certificate</strong> is available on every purchase line.</li>
    <li>A <strong>receipt</strong> is available on every payout.</li>
    <li>An <strong>estate certificate</strong> accompanies every payment to an heir.</li>
</ul>

<p>
    These documents also open through a <strong>signed link</strong>, valid for a
    limited time, which does not oblige the recipient to hold an account on the
    platform.
</p>

<h3>What a purchase certificate carries</h3>

<p>
    Besides the purchase it records, the certificate recalls the account's
    <strong>earlier acquisitions</strong>: date, number, nature, shares and amount,
    with the total at that date. A subscription is often made in several instalments,
    so the shareholder finds the whole of it on a single document. The recap does not
    appear on a first purchase, which would have nothing to recall.
</p>

<p>
    It stops at the date of the purchase being certified, never at today: a
    certificate states what was true on the day it was earned, and two printings of
    the same document look alike, months apart.
</p>

<p class="note">
    <strong>Acquired is not held.</strong> When the account has seen a redemption or a
    gift, the certificate adds the number of shares actually held at that date and says
    where the difference comes from. Likewise, the share coming from reinvested
    dividends is stated separately: it matches no payment by the shareholder.
</p>

<p class="note">
    <strong>On a waqf gift, each donor sees only their own.</strong> Gifted shares are
    recorded under the Waqf's institutional account, which receives the gifts of every
    donor. The certificate therefore recaps only its recipient's own gifts, and says
    nothing about that account's holding.
</p>

<p class="note">
    <strong>An export is a photograph, not a live link.</strong> A CSV produced today
    does not update itself. Date your files, or produce them again at the moment you
    need them: a three-month-old statement no longer states today's holding.
</p>
