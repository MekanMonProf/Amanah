<h2>Access to modules</h2>

<p>
    The grid crosses the <strong>roles</strong> — management, administration,
    account management, read-only — with the <strong>modules</strong> of the
    application. Three levels: none, read, write.
</p>

<p>
    A role without access does not see the entry in the side bar and cannot reach the
    page, even by typing its address. The same table commands the menu and the routes:
    they cannot contradict each other.
</p>

<p class="note">
    <strong>The administrator always keeps access to the settings.</strong> Without
    that lock, a badly set grid would close on itself and it would take a trip through
    the database to get out.
</p>

<h2>User accounts</h2>

<p>
    Create an account, change its role, deactivate it, reset its password. A password
    created here is temporary: its holder will have to choose another on first
    sign-in.
</p>

<p>
    Deactivating is better than deleting: the account stops opening the door, but
    everything it did stays attributed to someone in the audit log.
</p>

<h2>Financial settings</h2>

<p>
    The share price, and the two edge rules of the dividend:
</p>

<ul>
    <li><strong>End-of-month eligibility rule</strong> — a purchase made in the last days of the month only counts from the following month.</li>
    <li><strong>Mid-month exit rule</strong> — a redemption mid-month lets the shares earn that month's dividend.</li>
</ul>

<p>
    Both can also be set from the dividends page, where they are used.
</p>

<h2>File fields</h2>

<p>
    This is where it is decided, from a wider catalogue, which documents a file must
    contain to count as complete. Ticking a line brings it into the flag; unticking it
    takes it out, without removing it from the form.
</p>

<p>
    Before saving, the screen states how many files would be flagged under the current
    setting. Use that.
</p>

<p class="note">
    <strong>A signal that fires everywhere signals nothing.</strong> If nearly every
    file is flagged incomplete, it is not the database that needs correcting but this
    setting: require only the documents whose collection has actually begun, and tick
    the others as you go.
</p>

<h2>Help and support</h2>

<p>
    The contact details a team member sees when asking for help, the addresses of the
    videos that go with the manual, and the queue of requests received.
</p>

<p>
    An investor does not arrive here: their request goes to their own manager. They
    only fall back on platform support if their file has no manager assigned.
</p>

<h2>The audit log</h2>

<p>
    It is not among the settings but it is their counterpart: every setting changed
    here leaves a line there, with who, when, and the value before. The log is not
    written by hand and is not erased.
</p>
