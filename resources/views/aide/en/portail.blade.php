<h2>What you see on arriving</h2>

<p>
    <strong>My space</strong> opens on your holding: how many commercial shares you
    hold, how many waqf shares, and the total of your balances. That is the summary;
    the detail follows below, account by account.
</p>

<h2>Your accounts</h2>

<p>
    One file may carry several accounts. Each shows its category, its number, and
    whether automatic reinvestment is on.
</p>

<ul>
    <li><strong>Commercial</strong>: the shares that belong to you and earn you a dividend.</li>
    <li><strong>Waqf</strong>: shares given to the endowment. They confer no property right on you.</li>
</ul>

<p>
    <strong>Shares held</strong> is the number of shares as of today.
    <strong>Account balance</strong> is the money available: dividends that have not
    yet been reinvested or paid out.
</p>

<h2>Automatic reinvestment</h2>

<p>
    When it is on <strong>Yes</strong>, your dividend buys shares back as soon as it
    reaches the price of a whole share, and the remainder waits for the following
    month. That is why your number of shares rises on its own from one month to the
    next.
</p>

<p>
    When it is on <strong>No</strong>, the dividend builds up on the balance and you
    decide: leave it, buy, or ask for a payout.
</p>

<h2>Your purchases and movements</h2>

<p>
    The <strong>My purchases</strong> table lists every entry of shares, with its
    date, number and amount. Each line carries a <strong>certificate</strong> in PDF
    that you can open and keep.
</p>

<p>
    <strong>Latest movements</strong> shows the last ten entries on your account:
    dividends in green, what leaves in red. A share purchase appears as a negative —
    the money leaves the balance to become shares.
</p>

<h2>Your statement</h2>

<p>
    At the bottom of the page, <strong>Account statement</strong> produces a complete
    PDF. Leave both dates empty for the whole history, or bound a period — for a
    declaration, for a calendar year.
</p>

<p class="note">
    <strong>A line surprises you?</strong> Do not draw a conclusion before asking. The
    <strong>Contact support</strong> button sends your question to your manager, who
    has the detail in front of them. Give the date and the amount of the line in
    question.
</p>
