<h2>Redeeming shares</h2>

<p>
    A redemption takes shares out of the account and credits the matching capital to
    the account balance. It starts from the investor's file, through the
    <code>⋯</code> menu on the account header, entry <strong>Redemption</strong>.
</p>

<p>
    The button does not appear on categories where redemption is not allowed — waqf
    shares, in particular, are not taken back.
</p>

<ol>
    <li>State the number of shares redeemed and the real date of the exit.</li>
    <li>The capital is calculated and credited to the account balance.</li>
    <li>Paying the investor is a second, separate operation.</li>
</ol>

<p class="note">
    <strong>Redeeming is not paying.</strong> The redemption puts the money on the
    balance; it stays there until a <strong>Payout</strong> takes it out. A redeemed
    account whose balance has not been paid stays visible under "Redemptions
    pending", on the dashboard.
</p>

<h2>Paying the capital</h2>

<p>
    On the account header, <strong>Payout</strong>. The screen recognises that this is
    the capital of a redemption and says so. Enter the real means of payment — cash,
    bank transfer, Wave, Orange Money — it will appear on the receipt.
</p>

<p>
    Every payout produces a <strong>receipt</strong> in PDF, downloadable from the
    entry line, and a <strong>certificate</strong> reachable through a signed link
    that does not oblige the recipient to hold an account.
</p>

<h2>The redemption date and the dividend</h2>

<p>
    Shares redeemed mid-month earn that month's dividend, according to the exit rule
    set on the dividends page. That is why the <strong>real date</strong> of the
    redemption matters: entering it as the 1st of the following month would deprive
    the investor of a month that is owed to them.
</p>

<h2>Finding the history</h2>

<p>
    Each account carries the list of its redemptions, with the number, the date, the
    quantity and the means of settlement. The whole exports from
    <strong>Exports</strong>, as CSV or PDF, over a chosen period.
</p>

<p class="note">
    <strong>A redemption cannot be cancelled</strong> from the screen. If it is wrong,
    it is an adjustment entry — reserved for management — that puts the balance right,
    and the correction stays readable next to the mistake.
</p>
