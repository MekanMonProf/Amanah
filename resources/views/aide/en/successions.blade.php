<h2>Reporting a death</h2>

<p>
    From the investor's file, at the bottom, under <strong>Rare actions</strong>:
    <strong>Report a death</strong>. The file moves to the status
    <em>deceased</em> and its accounts are <strong>frozen</strong>.
</p>

<p>
    A frozen account accepts no ordinary operation: no purchase, no top-up, no payout,
    no gift, no redemption. Only the estate distribution can still touch it, through
    its dedicated screen.
</p>

<p class="note">
    <strong>Portal access is cut.</strong> If the deceased had a sign-in account,
    revoke it: the file keeps the <strong>Revoke access</strong> button for a deceased
    file precisely because that is where it serves most.
</p>

<h2>The estate documents</h2>

<p>
    A deceased file requires more documents than the others: the death certificate,
    and for the representative — the first heir named — their identity document, the
    certificate of inheritance or deed of notoriety, and the power of attorney signed
    by the family.
</p>

<p>
    These documents are <strong>flagged, not required</strong>: an estate often opens
    before the family has gathered its papers, and blocking the appointment would hold
    up everything else. A representative's document is counted as provided as soon as
    any heir carries it — it is the estate file that is judged complete, not a
    particular person.
</p>

<h2>Naming the heirs</h2>

<p>
    <strong>Estates</strong> in the bar, then the file concerned.
    <strong>Manage the estate</strong> allows heirs to be added and each one's share
    to be set. The first named acts as representative.
</p>

<h2>Dividing and paying</h2>

<p>
    For <strong>commercial</strong> accounts, the family chooses, share by share:
</p>

<ul>
    <li><strong>Transfer</strong>: the shares pass to the heir's file, who becomes an investor in turn. If they have no file, one is opened.</li>
    <li><strong>Payment</strong>: the share is liquidated and paid in money.</li>
</ul>

<p>
    For <strong>waqf</strong> accounts there is no choice: the capital returns to the
    charitable endowment. Those shares were never transmissible property.
</p>

<p>
    Every payment produces an <strong>estate certificate</strong> in PDF, in the
    heir's name.
</p>

<p class="note">
    <strong>Check the shares before launching the distribution.</strong> Once the
    shares are transferred and the payments written, going back takes adjustment
    entries across several files at once.
</p>
