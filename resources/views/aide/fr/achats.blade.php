<h2>Enregistrer un achat</h2>

<p>
    Depuis la fiche d'un investisseur, <strong>+ Nouvel achat</strong>. Vous choisissez
    la catégorie — commercial ou waqf — le nombre d'actions, la date et le mode de
    paiement. Le montant se déduit du prix de l'action en vigueur.
</p>

<p>
    Si le compte de la catégorie choisie n'existe pas encore, il est ouvert au
    passage. Un investisseur peut donc entrer par un achat waqf et n'avoir jamais de
    compte commercial.
</p>

<p class="note">
    <strong>La date compte.</strong> Un achat enregistré dans les tout derniers jours
    du mois ne donne droit au dividende qu'à partir du mois suivant. Le nombre de
    jours se règle dans <strong>Dividendes → Règle d'éligibilité en fin de mois</strong>.
    Saisissez la date réelle de l'achat, pas celle de la saisie.
</p>

<h2>Compléter un solde</h2>

<p>
    <strong>Complément</strong>, sur l'en-tête du compte, sert quand l'investisseur
    verse de l'argent sans acheter immédiatement : son solde financier monte, et
    l'achat se fera plus tard.
</p>

<p>
    <strong>Acheter avec le solde</strong> fait l'inverse : il transforme un solde
    déjà constitué en actions, sans attendre la prochaine distribution. Le bouton
    n'apparaît que sur les comptes dont le réinvestissement automatique est éteint —
    sur les autres, l'opération se fait d'elle-même chaque mois.
</p>

<h2>Verser de l'argent à un investisseur</h2>

<p>
    <strong>Paiement</strong> sort de l'argent du solde financier vers
    l'investisseur. L'écriture porte le mode de paiement et produit un
    <strong>reçu</strong> en PDF.
</p>

<p>
    Le bouton disparaît sur les catégories où le versement de dividendes n'est pas
    permis. Mieux vaut ne pas proposer l'opération que de la refuser après coup.
</p>

<h2>Offrir des actions</h2>

<p>
    <strong>Don</strong> transfère des actions ou un solde d'un compte à un autre sans
    contrepartie financière pour le donateur. Deux formes :
</p>

<ul>
    <li><strong>Don d'actions</strong> : les actions changent de propriétaire.</li>
    <li><strong>Don du solde</strong> : c'est l'argent disponible qui est cédé.</li>
</ul>

<p>
    Un cas particulier existe à l'achat : le <strong>présent waqf</strong>. L'achat est
    payé par une personne et versé au Waqf caritatif au nom d'une autre — en mémoire
    d'un défunt, ou en l'honneur de quelqu'un. Ces actions ne confèrent aucun droit
    patrimonial à la personne honorée ; elles apparaissent sur sa fiche dans un bloc à
    part.
</p>

<p class="note">
    <strong>Le don est définitif.</strong> Il n'y a pas d'annulation : seule une
    écriture d'ajustement, réservée à la direction, peut rattraper une erreur — et
    elle laisse une trace, ce qui est le but.
</p>

<h2>Corriger une erreur</h2>

<p>
    <strong>Ajustement</strong>, derrière le menu <code>⋯</code> de l'en-tête du
    compte, est réservé à la direction et à l'administration. Il écrit une ligne qui
    corrige le solde, avec son motif. Rien n'est réécrit, rien n'est effacé :
    l'erreur et sa correction restent toutes deux lisibles dans l'historique.
</p>
