<h2>Se connecter</h2>

<p>
    L'application s'ouvre sur l'écran de connexion. Deux identifiants fonctionnent :
    votre <strong>adresse email</strong>, ou le <strong>numéro de téléphone</strong>
    inscrit à votre dossier. La plupart des investisseurs n'ont pas d'email et se
    connectent avec leur numéro.
</p>

<p>
    Le numéro s'écrit comme vous voulez : <code>77 123 45 67</code>,
    <code>00221771234567</code> ou <code>+221771234567</code> désignent le même
    numéro, l'application les ramène toutes à la même forme avant de chercher.
</p>

<p class="note">
    <strong>Première connexion.</strong> Un mot de passe créé par un gestionnaire est
    temporaire : l'application vous demandera d'en choisir un autre avant de vous
    laisser entrer. C'est normal, et c'est la raison pour laquelle le mot de passe
    reçu par message ne sert qu'une fois.
</p>

<h2>Se repérer</h2>

<p>
    La barre de gauche rassemble tout ce à quoi vous avez accès, groupé par domaine —
    <strong>Gestion</strong>, <strong>Finance</strong>, <strong>Administration</strong>,
    <strong>Aide</strong>. Vous ne voyez que les entrées que votre rôle autorise : une
    barre courte n'est pas une barre incomplète.
</p>

<ul>
    <li>Le chevron en haut de la barre la replie en icônes, pour gagner de la largeur.</li>
    <li>Sur téléphone, la barre devient un tiroir et les entrées les plus fréquentes passent en bas de l'écran.</li>
    <li>Le haut de chaque page rappelle en petites capitales le domaine où vous êtes.</li>
</ul>

<h2>Changer de langue</h2>

<p>
    Les trois langues — français, anglais, arabe — se choisissent en haut à droite.
    Le choix est gardé sur votre compte : vous le faites une fois. En arabe,
    l'application se retourne entièrement, la barre passe à droite et les tableaux
    se lisent de droite à gauche.
</p>

<p>
    Avant d'être connecté, le même sélecteur est sous le formulaire. Le choix ne vit
    alors que le temps de la visite, faute de compte où l'inscrire.
</p>

<h2>Votre compte</h2>

<p>
    En bas de la barre, votre nom ouvre un menu court : <strong>Profil</strong> pour
    changer votre mot de passe, votre langue ou activer la double authentification, et
    <strong>Déconnexion</strong>.
</p>

<p class="note">
    <strong>Si vous êtes bloqué.</strong> N'insistez pas plus de cinq fois sur l'écran
    de connexion : au-delà, l'accès se ferme quelques minutes. Passez plutôt par
    <strong>Contacter le support</strong>, ou demandez à votre gestionnaire de
    réinitialiser votre mot de passe.
</p>
