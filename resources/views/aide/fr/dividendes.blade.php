<h2>Le principe</h2>

<p>
    Chaque mois, la maison fixe un <strong>bénéfice par action</strong> — un pour les
    actions commerciales, un pour les actions waqf. L'application multiplie ce taux
    par le nombre d'actions que chaque compte détenait sur la période, et écrit le
    dividende.
</p>

<p>
    Un taux se fixe <strong>une seule fois</strong> pour un mois donné. Il est
    définitif : une erreur se répare par une correction tracée, pas par une
    réécriture silencieuse.
</p>

<h2>Distribuer</h2>

<ol>
    <li>Ouvrez <strong>Dividendes</strong>.</li>
    <li>Choisissez le mois concerné.</li>
    <li>Saisissez le bénéfice par action, commercial et waqf.</li>
    <li>Cliquez sur <strong>Calculer et distribuer</strong>.</li>
</ol>

<p class="note">
    <strong>Chaque lancement rejoue tout l'historique</strong>, pas seulement le mois
    choisi. Un compte ouvert après coup rattrape ainsi tous les mois qu'il a manqués,
    au taux qui était en vigueur à chaque période. Un compte qui a déjà reçu son
    dividende pour un mois ne le reçoit pas deux fois.
</p>

<h2>Les deux règles de bord</h2>

<p>
    Un mois a deux extrémités, et chacune a sa règle, réglable sur la page des
    dividendes.
</p>

<h3>À l'entrée — règle d'éligibilité en fin de mois</h3>

<p>
    Un achat effectué dans les derniers jours du mois ne compte qu'à partir du mois
    suivant. Le nombre de jours se règle ; à zéro, tout achat compte immédiatement.
</p>

<h3>À la sortie — règle de sortie en cours de mois</h3>

<p>
    Une radiation effectuée en cours de mois laisse les actions toucher le dividende
    de ce mois-là. C'est la pratique de la maison : qui sort le 15 reçoit le mois
    entier. Le réglage par défaut est de 31 jours, c'est-à-dire le mois complet ;
    à zéro, les actions cessent de compter dès la radiation.
</p>

<p>
    Ces deux règles sont lues à l'identique par le calcul des dividendes et par la
    commande de contrôle de cohérence : elles ne peuvent pas diverger.
</p>

<h2>Corriger un taux</h2>

<p>
    Dans l'historique des barèmes, <strong>Corriger Com.</strong> et
    <strong>Corriger Waqf</strong> ouvrent la correction d'une période déjà fixée.
    L'application recalcule les dividendes concernés et écrit la différence —
    en plus ou en moins — sur chaque compte touché.
</p>

<p class="note">
    <strong>Vérifiez le nombre de comptes concernés</strong> avant de valider. Une
    correction sur un mois ancien touche tous ceux qui détenaient des actions à cette
    date, y compris ceux qui sont sortis depuis.
</p>

<h2>Ce que le dividende devient</h2>

<p>
    Il tombe sur le solde financier du compte. Ce qu'il en advient dépend du
    réinvestissement automatique : actif, il rachète des actions entières dès que le
    solde le permet, et garde le reste pour le mois suivant ; inactif, il attend
    qu'on en décide.
</p>
