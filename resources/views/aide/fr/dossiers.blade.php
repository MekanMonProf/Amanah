<h2>Ouvrir un dossier</h2>

<p>
    Depuis <strong>Investisseurs</strong>, le bouton <strong>Nouveau dossier</strong>
    ne demande que l'essentiel : un nom, un numéro. C'est volontaire — une
    souscription ne doit pas attendre que les papiers soient réunis. Le reste se
    saisit plus tard.
</p>

<p>
    L'identifiant du dossier est attribué par l'application. Le numéro de téléphone
    peut s'écrire dans n'importe quelle forme : il est ramené au format international
    avant d'être enregistré.
</p>

<h2>Compléter le dossier</h2>

<p>
    Un dossier auquel il manque une pièce réclamée est signalé : en haut de sa fiche,
    une ligne annonce ce qui manque et mène directement au formulaire. La liste
    <strong>Investisseurs</strong> a un filtre pour les retrouver tous.
</p>

<p>
    Ce qui est réclamé n'est pas figé : c'est l'onglet <strong>Champs du dossier</strong>
    du paramétrage qui décide, parmi un catalogue plus large, quelles lignes comptent.
    Une pièce décochée disparaît du signalement sans disparaître du formulaire.
</p>

<p class="note">
    <strong>Rien ne bloque.</strong> Un dossier incomplet reste pleinement utilisable :
    on peut y enregistrer des achats, lui verser des dividendes, le radier. Le
    signalement est un rappel, pas un verrou — arrêter la collecte pour une pièce
    manquante coûterait plus cher que le risque qu'on veut réduire.
</p>

<h2>Donner l'accès au portail</h2>

<p>
    Sur la fiche, <strong>Créer un accès au portail investisseur</strong> ouvre un
    compte de connexion à l'investisseur. L'application génère un mot de passe
    temporaire et l'affiche à l'écran, avec un bouton qui prépare le message WhatsApp.
</p>

<ol>
    <li>Cliquez sur le bouton WhatsApp : votre application s'ouvre, le message est déjà écrit.</li>
    <li>Vous l'envoyez vous-même, depuis votre propre compte.</li>
    <li>L'investisseur devra changer ce mot de passe à sa première connexion.</li>
</ol>

<p>
    Trois états, et non deux : un accès peut être <strong>révoqué</strong> sans être
    effacé, puis rétabli. La révocation coupe la session en cours ; le dossier, les
    parts et l'historique n'y touchent pas.
</p>

<p class="note">
    <strong>La plateforme n'envoie rien toute seule.</strong> Elle prépare le message,
    vous l'envoyez. Aucun envoi automatique, donc aucune preuve d'envoi : si
    l'investisseur dit n'avoir rien reçu, vérifiez votre propre conversation WhatsApp.
</p>

<h2>Changer de gestionnaire</h2>

<p>
    Le bloc <strong>Gestionnaire</strong> de la fiche porte un lien
    <strong>Changer</strong>, réservé à la direction et à l'administration. Le
    transfert est inscrit au journal d'audit, avec l'ancien et le nouveau titulaire.
</p>

<h2>Désactiver un dossier</h2>

<p>
    En bas de la fiche, sous <strong>Actes rares</strong>. Désactiver coupe l'accès au
    portail et sort le dossier des listes courantes, sans rien effacer. L'opération se
    défait : le même bouton propose alors <strong>Réactiver</strong>.
</p>

<p>
    Un décès ne se traite pas ici mais par <strong>Déclarer un décès</strong>, qui
    ouvre une succession. Voir la page correspondante.
</p>
