<h2>Les exports globaux</h2>

<p>
    L'écran <strong>Exports</strong> rassemble les sorties qui portent sur toute la
    base : achats, écritures financières, radiations, journal d'audit. Chacune existe
    en <strong>CSV</strong> — pour retravailler dans un tableur — et en
    <strong>PDF</strong> — pour transmettre ou archiver.
</p>

<p>
    Les deux champs de date bornent la période. Laissés vides, ils donnent tout
    l'historique.
</p>

<h2>Les exports d'un compte</h2>

<p>
    Les mêmes sorties existent compte par compte, depuis la fiche de l'investisseur :
    les boutons <strong>CSV</strong> et <strong>PDF</strong> au-dessus de chaque
    tableau — historique des achats, écritures du compte financier — n'exportent que
    ce qu'ils surmontent, filtres compris.
</p>

<h2>Le relevé de compte</h2>

<p>
    En bas de la fiche d'un investisseur, <strong>Relevé de compte</strong> produit un
    document à l'en-tête de la maison, qui rassemble sa position, ses achats et ses
    mouvements sur la période demandée. C'est le document à envoyer à un investisseur
    qui demande « où j'en suis ».
</p>

<p>
    L'investisseur qui a un accès au portail peut le sortir lui-même depuis
    <strong>Mon espace</strong>.
</p>

<h2>Attestations et reçus</h2>

<ul>
    <li>Une <strong>attestation d'achat</strong> est disponible sur chaque ligne d'achat.</li>
    <li>Un <strong>reçu</strong> est disponible sur chaque versement.</li>
    <li>Une <strong>attestation de succession</strong> accompagne chaque versement à un héritier.</li>
</ul>

<p>
    Ces documents s'ouvrent aussi par un <strong>lien signé</strong>, valable un temps
    limité, qui n'oblige pas le destinataire à avoir un compte sur la plateforme.
</p>

<p class="note">
    <strong>Un export est une photographie, pas un lien vivant.</strong> Un CSV sorti
    aujourd'hui ne se met pas à jour. Datez vos fichiers, ou ressortez-les au moment
    de vous en servir : un relevé de trois mois ne dit plus la position d'aujourd'hui.
</p>
