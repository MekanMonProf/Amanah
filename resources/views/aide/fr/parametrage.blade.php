<h2>Accès aux modules</h2>

<p>
    La grille croise les <strong>rôles</strong> — direction, administration, gestion,
    lecture — et les <strong>modules</strong> de l'application. Trois niveaux :
    aucun, lecture, écriture.
</p>

<p>
    Un rôle sans accès ne voit pas l'entrée dans la barre latérale et ne peut pas
    atteindre la page, même en tapant son adresse. C'est la même table qui commande
    le menu et les routes : elles ne peuvent pas se contredire.
</p>

<p class="note">
    <strong>L'administrateur garde toujours l'accès au paramétrage.</strong> Sans ce
    verrou, une grille mal réglée se refermerait sur elle-même et il faudrait repasser
    par la base de données pour en sortir.
</p>

<h2>Comptes utilisateurs</h2>

<p>
    Créer un compte, changer son rôle, le désactiver, réinitialiser son mot de passe.
    Un mot de passe créé ici est temporaire : son titulaire devra en choisir un autre
    à la première connexion.
</p>

<p>
    Désactiver vaut mieux que supprimer : le compte cesse d'ouvrir la porte, mais
    tout ce qu'il a fait reste attribué à quelqu'un dans le journal d'audit.
</p>

<h2>Paramètres financiers</h2>

<p>
    Le prix de l'action, et les deux règles de bord du dividende :
</p>

<ul>
    <li><strong>Règle d'éligibilité en fin de mois</strong> — un achat fait dans les derniers jours du mois ne compte qu'au mois suivant.</li>
    <li><strong>Règle de sortie en cours de mois</strong> — une radiation en cours de mois laisse les actions toucher le dividende de ce mois-là.</li>
</ul>

<p>
    Les deux se règlent aussi depuis la page des dividendes, où elles servent.
</p>

<h2>Champs du dossier</h2>

<p>
    C'est ici qu'on décide, parmi un catalogue plus large, quelles pièces un dossier
    doit contenir pour être tenu pour complet. Cocher une ligne la fait entrer dans le
    signalement ; la décocher l'en sort, sans la retirer du formulaire.
</p>

<p>
    L'écran annonce, avant d'enregistrer, combien de dossiers seraient signalés avec
    le réglage courant. Servez-vous-en.
</p>

<p class="note">
    <strong>Un signal qui se déclenche partout ne signale plus rien.</strong> Si la
    quasi-totalité des dossiers est signalée incomplète, ce n'est pas la base qu'il
    faut corriger mais ce réglage : ne réclamez que les pièces dont la collecte a
    réellement commencé, et cochez les autres à mesure.
</p>

<h2>Aide et support</h2>

<p>
    Les coordonnées que voit un membre de l'équipe quand il demande de l'aide, les
    adresses des vidéos qui accompagnent le mode d'emploi, et la file des demandes
    reçues.
</p>

<p>
    Un investisseur, lui, n'arrive pas ici : sa demande part vers son propre
    gestionnaire. Il ne retombe sur le support de la plateforme que si son dossier
    n'a pas de gestionnaire assigné.
</p>

<h2>Le journal d'audit</h2>

<p>
    Il n'est pas dans le paramétrage mais il en est le complément : tout réglage
    changé ici y laisse une ligne, avec qui, quand, et la valeur d'avant. Le journal
    ne s'écrit pas à la main et ne s'efface pas.
</p>
