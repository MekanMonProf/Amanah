<h2>Ce que vous voyez en arrivant</h2>

<p>
    <strong>Mon espace</strong> s'ouvre sur votre position : le nombre d'actions
    commerciales que vous détenez, le nombre d'actions waqf, et le total de vos
    soldes. C'est le résumé ; le détail vient dessous, compte par compte.
</p>

<h2>Vos comptes</h2>

<p>
    Un dossier peut porter plusieurs comptes. Chacun affiche sa catégorie, son
    numéro, et si le réinvestissement automatique y est actif.
</p>

<ul>
    <li><strong>Commercial</strong> : les actions qui vous appartiennent et vous rapportent un dividende.</li>
    <li><strong>Waqf</strong> : les actions versées à l'œuvre. Elles ne vous confèrent aucun droit patrimonial.</li>
</ul>

<p>
    <strong>Actions détenues</strong> est le nombre d'actions à ce jour.
    <strong>Solde du compte financier</strong> est l'argent disponible : les
    dividendes qui n'ont pas encore été réinvestis ni versés.
</p>

<h2>Réinvestissement automatique</h2>

<p>
    Quand il est sur <strong>Oui</strong>, votre dividende rachète des actions dès
    qu'il atteint le prix d'une action entière, et le reste attend le mois suivant.
    C'est ce qui explique que votre nombre d'actions monte tout seul d'un mois sur
    l'autre.
</p>

<p>
    Quand il est sur <strong>Non</strong>, le dividende s'accumule sur le solde et
    vous décidez : le laisser, acheter, ou demander un versement.
</p>

<h2>Vos achats et vos mouvements</h2>

<p>
    Le tableau <strong>Mes achats</strong> liste chaque entrée d'actions, avec sa
    date, son nombre et son montant. Chaque ligne porte une
    <strong>attestation</strong> en PDF, que vous pouvez ouvrir et garder.
</p>

<p>
    <strong>Derniers mouvements</strong> montre les dix dernières écritures de votre
    compte financier : les dividendes en vert, ce qui en sort en rouge. Un achat
    d'action apparaît en négatif — l'argent quitte le solde pour devenir des actions.
</p>

<h2>Votre relevé</h2>

<p>
    En bas de page, <strong>Relevé de compte</strong> produit un PDF complet. Laissez
    les deux dates vides pour tout l'historique, ou bornez une période — pour une
    déclaration, pour une année civile.
</p>

<p class="note">
    <strong>Une ligne vous surprend ?</strong> N'en tirez pas de conclusion avant
    d'avoir demandé. Le bouton <strong>Contacter le support</strong> envoie votre
    question à votre gestionnaire, qui a le détail sous les yeux. Indiquez la date
    et le montant de la ligne en question.
</p>
