<h2>Radier des actions</h2>

<p>
    La radiation sort des actions du compte et crédite le capital correspondant sur le
    solde financier. Elle se lance depuis la fiche de l'investisseur, par le menu
    <code>⋯</code> de l'en-tête du compte, entrée <strong>Radiation</strong>.
</p>

<p>
    Le bouton n'apparaît pas sur les catégories où la radiation n'est pas permise —
    les actions waqf, notamment, ne se reprennent pas.
</p>

<ol>
    <li>Indiquez le nombre d'actions radiées et la date réelle de la sortie.</li>
    <li>Le capital est calculé et crédité sur le solde financier du compte.</li>
    <li>Le versement à l'investisseur est une seconde opération, distincte.</li>
</ol>

<p class="note">
    <strong>Radier n'est pas payer.</strong> La radiation met l'argent sur le solde ;
    il y reste jusqu'à ce qu'un <strong>Paiement</strong> le sorte. Un compte radié
    dont le solde n'est pas versé reste visible dans « Radiations en attente », sur
    le tableau de bord.
</p>

<h2>Verser le capital</h2>

<p>
    Sur l'en-tête du compte, <strong>Paiement</strong>. L'écran reconnaît qu'il s'agit
    du capital d'une radiation et l'annonce. Renseignez le mode de paiement réel —
    espèces, virement, Wave, Orange Money — il figurera sur le reçu.
</p>

<p>
    Chaque versement produit un <strong>reçu</strong> en PDF, téléchargeable depuis la
    ligne d'écriture, et une <strong>attestation</strong> consultable par un lien
    signé qui n'oblige pas le destinataire à avoir un compte.
</p>

<h2>La date de radiation et le dividende</h2>

<p>
    Les actions radiées en cours de mois touchent le dividende de ce mois-là, selon la
    règle de sortie réglée sur la page des dividendes. C'est pourquoi la
    <strong>date réelle</strong> de la radiation compte : la saisir au 1er du mois
    suivant priverait l'investisseur d'un mois qui lui revient.
</p>

<h2>Retrouver l'historique</h2>

<p>
    Chaque compte porte la liste de ses radiations, avec le numéro, la date, la
    quantité et le mode de règlement. L'ensemble s'exporte depuis
    <strong>Exports</strong>, en CSV ou en PDF, sur une période choisie.
</p>

<p class="note">
    <strong>Une radiation ne s'annule pas</strong> depuis l'écran. Si elle est
    erronée, c'est une écriture d'ajustement — réservée à la direction — qui rattrape
    le solde, et la correction reste lisible à côté de l'erreur.
</p>
