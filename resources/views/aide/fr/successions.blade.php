<h2>Déclarer un décès</h2>

<p>
    Depuis la fiche de l'investisseur, en bas, sous <strong>Actes rares</strong> :
    <strong>Déclarer un décès</strong>. Le dossier passe au statut
    <em>décédé</em> et ses comptes sont <strong>gelés</strong>.
</p>

<p>
    Un compte gelé n'accepte plus aucune opération courante : ni achat, ni complément,
    ni paiement, ni don, ni radiation. Seule la répartition de succession peut encore
    le toucher, par son écran dédié.
</p>

<p class="note">
    <strong>L'accès au portail se coupe.</strong> Si le défunt avait un compte de
    connexion, révoquez-le : la fiche garde le bouton <strong>Révoquer l'accès</strong>
    pour un dossier décédé, précisément parce que c'est là qu'il sert le plus.
</p>

<h2>Les pièces de la succession</h2>

<p>
    Un dossier décédé réclame des pièces de plus que les autres : l'acte de décès, et
    pour le mandataire — le premier héritier désigné — sa pièce d'identité, le
    certificat d'hérédité ou acte de notoriété, et la procuration signée par la
    famille.
</p>

<p>
    Ces pièces sont <strong>signalées, pas exigées</strong> : une succession s'ouvre
    souvent avant que la famille n'ait réuni ses papiers, et bloquer la désignation
    retarderait tout le reste. Une pièce du mandataire est tenue pour fournie dès
    qu'un héritier la porte — c'est le dossier de succession qu'on juge complet, pas
    telle personne.
</p>

<h2>Désigner les héritiers</h2>

<p>
    <strong>Successions</strong> dans la barre, puis le dossier concerné.
    <strong>Gérer la succession</strong> permet d'ajouter les héritiers et de fixer la
    part de chacun. Le premier désigné tient le rôle de mandataire.
</p>

<h2>Répartir et verser</h2>

<p>
    Pour les comptes <strong>commerciaux</strong>, la famille choisit, part par part :
</p>

<ul>
    <li><strong>Transfert</strong> : les actions passent au dossier de l'héritier, qui devient investisseur à son tour. S'il n'a pas de dossier, il s'en ouvre un.</li>
    <li><strong>Paiement</strong> : la part est liquidée et versée en argent.</li>
</ul>

<p>
    Pour les comptes <strong>waqf</strong>, il n'y a pas de choix : le capital rejoint
    l'œuvre caritative. Ces actions n'ont jamais été un patrimoine transmissible.
</p>

<p>
    Chaque versement produit une <strong>attestation de succession</strong> en PDF, au
    nom de l'héritier.
</p>

<p class="note">
    <strong>Vérifiez les parts avant de lancer la répartition.</strong> Une fois les
    actions transférées et les versements écrits, revenir en arrière demande des
    écritures d'ajustement sur plusieurs dossiers à la fois.
</p>
